// Generates db/seed.sql from db/template-content.js.  Run: npm run db:build-seed
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FRAMEWORKS, MATRIX, OVERLAYS, BASE, SPECIFIC } from './template-content.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

export function buildSections(type, code) {
  const b = BASE[type];
  const o = OVERLAYS[code];
  const join = (...parts) => parts.flat().filter(Boolean).join('\n');
  return [
    { title: 'Purpose', body: join(b.purpose, o.purpose) },
    { title: 'Scope', body: b.scope },
    { title: 'Definitions', body: join(b.definitions) },
    { title: 'Roles & Responsibilities', body: join(
      `• Senior Management: approve this policy, provide the resources needed to implement it and lead by example.`,
      `• ${b.lead}: own and maintain this policy, monitor compliance and report performance to senior management.`,
      '• Line Managers: make sure their teams understand and follow this policy, and act promptly on concerns raised.',
      '• All Employees and Contractors: follow this policy, complete required training and report concerns without delay.',
    ) },
    { title: 'Procedure', body: join(b.procedure, o.procedure, SPECIFIC[`${type}|${code}`] || []) },
    { title: 'Training', body: join(b.training) },
    { title: 'Reporting', body: join(b.reporting, o.reporting) },
    { title: 'Review & Approval', body: join(
      'This policy is effective from {{effective_date}} and will be reviewed by {{review_date}}, or sooner after a significant incident, a change in law or regulation, an audit finding or a material change to {{company_name}}\'s operations.',
      o.review,
      'Approved by the senior management of {{company_name}}.',
    ) },
  ];
}

const lines = [
  '-- GIDO ComplyPilot seed data. GENERATED by db/build-seed.js; edit db/template-content.js instead.',
  '-- Safe to run repeatedly (upserts on unique keys).',
  '',
  '-- Frameworks',
];
for (const f of FRAMEWORKS) {
  lines.push(`INSERT INTO frameworks (code, name, description) VALUES (${q(f.code)}, ${q(f.name)}, ${q(f.description)})
  ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description;`);
}
lines.push('', '-- Policy templates');
let count = 0;
for (const [type, codes] of Object.entries(MATRIX)) {
  for (const code of codes) {
    const sections = buildSections(type, code);
    lines.push(`INSERT INTO policy_templates (policy_type, framework_id, sections)
  SELECT ${q(type)}, id, ${q(JSON.stringify(sections))}::jsonb FROM frameworks WHERE code = ${q(code)}
  ON CONFLICT (policy_type, framework_id) DO UPDATE SET sections = EXCLUDED.sections;`);
    count++;
  }
}
lines.push('');
fs.writeFileSync(path.join(here, 'seed.sql'), lines.join('\n'));
console.log(`seed.sql written: ${FRAMEWORKS.length} frameworks, ${count} templates`);
